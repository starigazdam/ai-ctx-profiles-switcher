function Get-CtxSubdirName {
    param([string]$Base)
    if (Test-Path -LiteralPath $Base -PathType Container) {
        Get-ChildItem -LiteralPath $Base -Directory | Select-Object -ExpandProperty Name
    }
}

Register-ArgumentCompleter -CommandName ctx -ScriptBlock {
    param($wordToComplete, $commandAst)

    $root = Get-CtxRoot
    $elements = $commandAst.CommandElements
    # elements[0] is 'ctx' itself; count how many positional args precede current one.
    $argIndex = $elements.Count - 1

    if ($argIndex -le 1) {
        $candidates = @('current', 'clear') + (Get-CtxSubdirName (Join-Path $root 'profiles'))
    } elseif ($argIndex -eq 2 -and $elements[1].Extent.Text -eq 'clear') {
        $candidates = @('--all')
    } else {
        $candidates = Get-CtxSubdirName (Join-Path $root 'shared')
    }

    $candidates |
        Where-Object { $_ -like "$wordToComplete*" } |
        Sort-Object -Unique |
        ForEach-Object { [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterValue', $_) }
}
