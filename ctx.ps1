# --- Tab completion --------------------------------------------------------

function Get-CtxSubdirName {
    param([string]$Base)
    if (Test-Path -LiteralPath $Base -PathType Container) {
        Get-ChildItem -LiteralPath $Base -Directory | Select-Object -ExpandProperty Name
    }
}

function Get-CtxProfileName {
    $names = @(Get-CtxSubdirName (Join-Path (Get-CtxRoot) 'profiles'))
    $externalRoot = Get-CtxExternalProfilesRoot
    if ($externalRoot) { $names += Get-CtxSubdirName $externalRoot }
    return $names | Sort-Object -Unique
}

Register-ArgumentCompleter -CommandName ctx -ScriptBlock {
    param($wordToComplete, $commandAst)

    $elements = $commandAst.CommandElements
    # elements[0] is 'ctx' itself; count how many positional args precede current one.
    $argIndex = $elements.Count - 1

    if ($argIndex -le 1) {
        $candidates = @('current', 'clear', 'skills', 'load') + (Get-CtxProfileName)
    } elseif ($argIndex -eq 2 -and $elements[1].Extent.Text -eq 'clear') {
        $candidates = @('--all')
    } elseif ($argIndex -ge 2 -and $elements[1].Extent.Text -eq 'load') {
        # File-system completion for ctx load — return matching paths.
        $searchDir = if ($wordToComplete) { Split-Path -Parent $wordToComplete } else { (Get-Location).Path }
        if (-not $searchDir) { $searchDir = (Get-Location).Path }
        if (Test-Path -LiteralPath $searchDir -PathType Container) {
            Get-ChildItem -LiteralPath $searchDir -Force |
                Where-Object { $_.Name -like "$(Split-Path -Leaf $wordToComplete)*" } |
                ForEach-Object {
                    $full = $_.FullName
                    [System.Management.Automation.CompletionResult]::new($full, $full, 'ParameterValue', $full)
                }
        }
        return
    } else {
        $candidates = Get-CtxProfileName
    }

    $candidates |
        Where-Object { $_ -like "$wordToComplete*" } |
        Sort-Object -Unique |
        ForEach-Object { [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterValue', $_) }
}
