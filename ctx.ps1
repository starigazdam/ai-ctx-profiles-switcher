#Requires -Version 5.1
<#
.SYNOPSIS
    ctx - Portable context switcher for GitHub Copilot CLI (PowerShell edition)

.DESCRIPTION
    Composes AI agent configuration directories (profiles)
    stored under a root directory (default: $HOME\work\ai-config) into the
    COPILOT_CUSTOM_INSTRUCTIONS_DIRS environment variable, for the current
    PowerShell session.

    Mirrors the behavior of ctx.sh (bash/zsh) so the same workflow works on
    Windows PowerShell and PowerShell 7+ (pwsh).

.NOTES
    INSTALLATION
    ------------
    1. Copy this file to a stable location, e.g.:
         %USERPROFILE%\.config\ctx\ctx.ps1
       (or run .\install.ps1 from this repo)

    2. Add to your PowerShell profile ($PROFILE):
         . "$HOME\.config\ctx\ctx.ps1"

    3. Tab completion and directory-change auto-loading are registered
       automatically when this file is dot-sourced.

    DIRECTORY LAYOUT EXPECTED
    -------------------------
        $env:AI_CTX_PROFILES_CONFIG_ROOT (default: $HOME\work\ai-config)
        `-- profiles\
            |-- review\
            |-- architecture\
            |-- incident\
            |-- coding\
            |-- dotnet\
            |-- azure\
            |-- terraform\
            `-- security\

    USAGE
    -----
        ctx review                    # activate the "review" profile
        ctx coding azure               # activate multiple profiles
        ctx review dotnet security     # activate multiple profiles
        ctx current                    # show active profiles/env vars
        ctx clear                      # unset AI_CTX_PROFILES / COPILOT_CUSTOM_INSTRUCTIONS_DIRS / COPILOT_HOME
        ctx clear --all                # remove the current context home and owned workspace artifacts
        ctx --help                     # usage help

    AUTO-LOADING (.ctx files)
    --------------------------
    Drop a ".ctx" file in any project directory. Each non-empty,
    non-comment line maps an arbitrary context name to a custom-instructions
    directory:

        <context-name>:<path-to-folder>

    Example:
        review:C:\work\ai-config\profiles\review
        dotnet:C:\work\ai-config\profiles\dotnet
        security:.\local-instructions

    Relative paths are resolved against the directory containing the .ctx
    file (not the current working directory). Unlike `ctx <profile>
    [profile...]`, these names are NOT looked up under AI_CTX_PROFILES_CONFIG_ROOT\profiles
    - the path on each line is used directly. Every path is validated
    to exist.

    When your prompt renders after a `cd`/`Set-Location` into that directory
    (or a descendant of it), AI_CTX_PROFILES and COPILOT_CUSTOM_INSTRUCTIONS_DIRS
    are set (overwriting any previous value) from the file's contents.
    Leaving the directory tree (into a location with no .ctx file)
    automatically clears the context.

    NOAUTOLOAD FLAG
    ----------------
    Add a bare "noautoload" line (no colon, case-insensitive) to the .ctx
    file to prevent the directory-change hook from loading it automatically:

        noautoload
        review:C:\work\ai-config\profiles\review

    The file remains valid and can be loaded explicitly at any time with
    "ctx load <path-to-.ctx-file>" (see below).

    SKILL DISCOVERY
    ---------------
    COPILOT_CUSTOM_INSTRUCTIONS_DIRS does not make Copilot CLI discover
    agent skills stored in your .ctx entries. ctx sets COPILOT_HOME to a
    per-context home and links each resolved entry's contracted skill source
    (.github\skills for legacy profiles, .agents\skills for canonical AGENTS.md
    profiles) into its skills folder. Shared Copilot files are reconciled
    against the real Copilot home on every activation. The cache remains after
    ctx clear; ctx clear --all removes it.

    VS CODE WORKSPACE
    ------------------
    Whenever a .ctx file is loaded, a multi-root VS Code workspace file
    named "<folder-name>.code-workspace" is created (or updated) next to
    it, so the project and its .ctx dependencies can all be browsed in one
    VS Code window:

        - This folder is added as "root: <folder-name>".
        - Each .ctx entry is added as "ctx: <context-name>", pointing at
          the resolved directory from that line.

    Any other folders already present in the workspace file (added by you,
    or by VS Code) are preserved; only entries previously generated by ctx
    (named "root: ..." or "ctx: ...") are replaced on each load. Nothing is
    removed from the workspace file when the context is cleared (run
    "ctx clear --all" to delete it instead).

    Disable this behavior for the session with:
        $env:CTX_AUTO_LOAD = "0"
#>

# --- Core implementation -------------------------------------------------

function Get-CtxRoot {
    if ($env:AI_CTX_PROFILES_CONFIG_ROOT) {
        return $env:AI_CTX_PROFILES_CONFIG_ROOT
    }
    return (Join-Path $HOME 'work\ai-config')
}

function Show-CtxUsage {
    @'
Usage:
  ctx <profile> [profile...]  Activate one or more profiles
  ctx current                   Show the currently active context
  ctx check                    Read-only audit against the nearest .ctx file
  ctx skills                   Read-only potential-Copilot-skill discovery
                               inventory (filesystem/configuration based)
  ctx clear                   Clear the currently active context
  ctx clear --all             Remove the current context home and generated
                               project artifacts next to the nearest .ctx file
                               Workspace files are removed only with the exact
                               generatedBy: "ctx" marker; unmarked, invalid,
                               and linked workspaces are preserved with a warning.
  ctx load <file>             Explicitly load a .ctx file (bypasses noautoload)
  ctx --help | -h             Show this help message

Examples:
  ctx review
  ctx coding azure
  ctx review dotnet security
  ctx load C:\path\to\project\.ctx

Environment:
  AI_CTX_PROFILES_CONFIG_ROOT      Root directory containing profiles\
                       (default: $HOME\work\ai-config)
  AI_CTX_PROFILES_EXTERNAL_PROFILES_ROOT
                       Optional absolute path to a trusted external profiles directory
  CTX_AUTO_LOAD        Set to 0 to disable automatic .ctx loading on cd
'@ | Write-Host
}

function Write-CtxStatus {
    param(
        [string]$ProfileName,
        [string]$SharedCsv
    )

    Write-Host ""
    Write-Host "[AI Context]"
    Write-Host ""
    Write-Host "Profile : $(if ($ProfileName) { $ProfileName } else { '<none>' })"
    Write-Host "Profiles: $(if ($SharedCsv) { $SharedCsv } else { '<none>' })"
    Write-Host ""
    Write-Host "AI_CTX_PROFILES=$(if ($env:AI_CTX_PROFILES) { $env:AI_CTX_PROFILES } else { '<unset>' })"
    if (Test-CtxActiveRecordMatches) {
        # Report the actually active mode from the matching activation
        # record, never the raw selector: a stale/mismatched
        # AI_CTX_PROFILES_COPILOT_MODE without a matching activation is not
        # reported as active.
        Write-Host "Mode: $(Get-CtxModeLabel -Mode $Script:CtxActiveMode)"
        if ($Script:CtxActiveMode -cne 'synthetic-home') {
            Write-Host "COPILOT_SKILLS_DIRS=$(if ($env:COPILOT_SKILLS_DIRS) { $env:COPILOT_SKILLS_DIRS } else { '<unset>' })"
        }
        Write-Host "COPILOT_HOME=$(if ($env:COPILOT_HOME) { $env:COPILOT_HOME } else { '<unset>' })"
    } else {
        # A context is active but there is no matching local activation
        # record: mode and any COPILOT_HOME/COPILOT_SKILLS_DIRS present are
        # unattributable, so label them unknown rather than guessing.
        Write-Host "Mode: <unknown>"
        if (Test-Path Env:\COPILOT_SKILLS_DIRS) { Write-Host "COPILOT_SKILLS_DIRS=$env:COPILOT_SKILLS_DIRS (unknown)" }
        if (Test-Path Env:\COPILOT_HOME) { Write-Host "COPILOT_HOME=$env:COPILOT_HOME (unknown)" } else { Write-Host "COPILOT_HOME=<unset>" }
    }
    Write-Host ""
    Write-Host "COPILOT_CUSTOM_INSTRUCTIONS_DIRS="
    if (Test-Path Env:\COPILOT_CUSTOM_INSTRUCTIONS_DIRS) {
        if ($env:COPILOT_CUSTOM_INSTRUCTIONS_DIRS) {
            ($env:COPILOT_CUSTOM_INSTRUCTIONS_DIRS -split ',') | ForEach-Object { Write-Host $_ }
        } else {
            Write-Host "<present-empty>"
        }
    } else {
        Write-Host "<unset>"
    }
}

function Show-CtxCurrent {
    if (-not $env:AI_CTX_PROFILES) {
        Write-Host "No active AI context."
        Write-Host 'Run "ctx <profile> [profile...]" to activate one.'
        return
    }

    $parts = $env:AI_CTX_PROFILES -split '\+'
    $profileName = $parts[0]
    $sharedCsv = ($parts | Select-Object -Skip 1) -join ', '

    Write-CtxStatus -ProfileName $profileName -SharedCsv $sharedCsv
}

function Clear-CtxContext {
    param([switch]$All)

    $prevContext = $env:AI_CTX_PROFILES
    $cleanupFailed = $false
    # Use the recorded mode of the matching activation, NOT the live selector
    # (which may be stale). With no matching record, home ownership is
    # unknown: ctx must never guess a mode from the selector or from the home
    # path, so COPILOT_HOME is left untouched and no home is deleted. Mode B
    # never touches COPILOT_HOME; Mode C never deletes the ephemeral home and
    # handles a drifted/replaced COPILOT_HOME separately below.
    $clearMode = Get-CtxActiveRecordMode
    # Capture COPILOT_HOME only where it is needed: the Mode A deletion safety
    # check (before the variable is unset below). Mode B clear and Mode C
    # clear never read it for ownership - Mode C uses the recorded ephemeral
    # path and Mode B leaves the variable untouched.
    $prevHome = $null
    if ($clearMode -ceq 'synthetic-home') {
        $prevHome = $env:COPILOT_HOME
    }
    Remove-Item Env:\AI_CTX_PROFILES -ErrorAction SilentlyContinue
    Remove-Item Env:\COPILOT_CUSTOM_INSTRUCTIONS_DIRS -ErrorAction SilentlyContinue
    switch ($clearMode) {
        'synthetic-home' {
            Remove-Item Env:\COPILOT_HOME -ErrorAction SilentlyContinue
        }
        'ephemeral-clean' {
            # Mode C: unset COPILOT_HOME only when it still exactly equals the
            # recorded ephemeral path; a user's replacement value is preserved.
            if ((Test-Path Env:\COPILOT_HOME) -and ($env:COPILOT_HOME -ceq $Script:CtxActiveHomeValue)) {
                Remove-Item Env:\COPILOT_HOME -ErrorAction SilentlyContinue
            }
        }
        default {
            # Mode B and unknown: never touch COPILOT_HOME.
        }
    }
    # Unset COPILOT_SKILLS_DIRS only when the current value still matches what
    # ctx established this session; a user's own or later value is left alone.
    Unset-CtxOwnedSkillsDirs
    # No matching activation record: report a present COPILOT_HOME as unknown
    # rather than attributing it to a mode or guessing a deletion target. On
    # the unknown path COPILOT_HOME is still set, so read it directly.
    if (-not $clearMode -and $env:COPILOT_HOME) {
        Write-Warning "ctx: warning: no matching activation record; COPILOT_HOME is unowned (unknown), left as-is: $($env:COPILOT_HOME)"
    }
    # The Mode C retained-path notice prints for BOTH plain clear and
    # clear --all, before the active record is cleared. A COPILOT_HOME that
    # no longer equals the recorded ephemeral path is preserved and reported
    # as changed/unowned.
    if ($clearMode -ceq 'ephemeral-clean') {
        if ($Script:CtxActiveHomeValue) {
            Write-CtxRetainedEphemeralHome -Path $Script:CtxActiveHomeValue
        }
        if ((Test-Path Env:\COPILOT_HOME) -and ($env:COPILOT_HOME -cne $Script:CtxActiveHomeValue)) {
            Write-Warning "ctx: warning: COPILOT_HOME has changed from the recorded ephemeral path (unowned, unknown), left as-is: $($env:COPILOT_HOME)"
        }
    }

    if ($All) {
        $dirOfFile = $Script:CtxAutoLoadDir
        if (-not $dirOfFile) {
            $ctxFile = Find-CtxFile
            if ($ctxFile) {
                $dirOfFile = Split-Path -Parent $ctxFile
            }
        }

        if ($dirOfFile) {
            # Legacy cleanup: settings.local.json's skillDirectories is
            # confirmed inert (issue #1) and no longer written by ctx, but
            # pre-existing files from older ctx versions are still removed
            # here for one release. Safe to drop this block in a future
            # release once users have upgraded.
            $settingsFile = Join-Path $dirOfFile '.github\copilot\settings.local.json'
            if (Test-Path -LiteralPath $settingsFile -PathType Leaf) {
                try {
                    Remove-Item -LiteralPath $settingsFile -Force -ErrorAction Stop
                    Write-Host "ctx: removed $settingsFile"
                } catch {
                    $cleanupFailed = $true
                    Write-Error "ctx: error: failed to remove $settingsFile`: $_" -ErrorAction Continue
                }
            }

            $folderName = Split-Path -Leaf (Resolve-Path -LiteralPath $dirOfFile).Path
            $workspaceFile = Join-Path $dirOfFile "$folderName.code-workspace"
            $workspaceItem = Get-Item -LiteralPath $workspaceFile -Force -ErrorAction SilentlyContinue
            if ($workspaceItem -and ($workspaceItem.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0) {
                Write-Warning "ctx: preserved linked workspace $workspaceFile"
            } elseif ($workspaceItem) {
                $workspaceOwned = $false
                try {
                    $workspaceData = Get-Content -LiteralPath $workspaceFile -Raw | ConvertFrom-Json
                    $workspaceOwned = ($workspaceData.generatedBy -is [string]) -and ($workspaceData.generatedBy -ceq 'ctx')
                } catch {
                    $workspaceOwned = $false
                }
                if ($workspaceOwned) {
                    try {
                        Remove-Item -LiteralPath $workspaceFile -Force -ErrorAction Stop
                        Write-Host "ctx: removed $workspaceFile"
                    } catch {
                        $cleanupFailed = $true
                        Write-Error "ctx: error: failed to remove $workspaceFile`: $_" -ErrorAction Continue
                    }
                } else {
                    Write-Warning "ctx: preserved unowned workspace $workspaceFile"
                }
            }
        } else {
            if ($prevContext) {
                # Context was activated manually (no .ctx file), so there are
                # no on-disk artifacts (settings.local.json / workspace file)
                # to clean up, but the COPILOT_HOME directory below still
                # gets removed - don't imply nothing happens at all.
                Write-Warning "ctx: warning: no .ctx file found; skipping artifact cleanup"
            } else {
                Write-Warning "ctx: warning: no .ctx file found; nothing to remove"
            }
        }

        # Mode B never touches COPILOT_HOME and skips the synthetic-home
        # deletion block entirely; Mode C never deletes the ephemeral home.
        # Only Mode A's existing safety-validated deletion runs.
        if ($clearMode -ceq 'synthetic-home' -and $prevContext) {
            if ($Script:CtxAutoLoadHomeOverride) {
                $homeDir = $Script:CtxAutoLoadHomeOverride
            } else {
                $sanitized = Get-CtxSanitizedContextName -Name $prevContext
                $homesRoot = Get-CtxCopilotHomeRoot
                $homeDir = Join-Path $homesRoot $sanitized
            }
            if (-not $prevHome -or $homeDir -ne $prevHome) {
                Write-Error "ctx: error: refusing to remove unsafe or unselected home: $homeDir" -ErrorAction Continue
                $cleanupFailed = $true
            } else {
                try { $null = Get-CtxValidatedHomePath -Path $homeDir } catch { Write-Error "ctx: error: $_" -ErrorAction Continue; $cleanupFailed = $true }
                if (-not $cleanupFailed -and (Test-Path -LiteralPath $homeDir -PathType Container) -and -not (Test-CtxIsLink -Path $homeDir)) {
                    try {
                        Remove-Item -LiteralPath $homeDir -Recurse -Force -ErrorAction Stop
                    } catch {
                        Write-Error "ctx: error: failed to remove $homeDir`: $_" -ErrorAction Continue
                        $cleanupFailed = $true
                    }
                    if (-not $cleanupFailed) {
                        Write-Host "ctx: removed $homeDir"
                    }
                }
            }
        }
    }

    # Never leave a stale active record for an already-cleared context, even
    # when --all reported an unrelated artifact cleanup error above.
    Reset-CtxActiveRecord
    $Script:CtxAutoLoadDir = $null
    $Script:CtxAutoLoadHomeOverride = $null
    Write-Host "AI context cleared."
    return (-not $cleanupFailed)
}

function Resolve-CtxProfileIdentifier {
    # Profiles are identifiers, not paths. Resolve only immediate children of
    # the configured root or the explicitly trusted external profiles root.
    param([string]$Name)
    if ([string]::IsNullOrWhiteSpace($Name) -or $Name -in @('.', '..') -or $Name -match '[\\/]') {
        throw "invalid profile identifier `"$Name`""
    }
    $profilesRoot = Join-Path (Get-CtxRoot) 'profiles'
    $externalRoot = Get-CtxExternalProfilesRoot
    $searchRoots = @($profilesRoot)
    if ($externalRoot) { $searchRoots += $externalRoot }
    $trustedRoots = @(Get-CtxTrustedProfileRoots)
    $comparison = if ($IsWindows -or $env:OS -ceq 'Windows_NT') { [System.StringComparison]::OrdinalIgnoreCase } else { [System.StringComparison]::Ordinal }
    foreach ($searchRoot in $searchRoots) {
        $candidate = Join-Path $searchRoot $Name
        if (-not (Test-Path -LiteralPath $candidate -PathType Container)) { continue }
        $canonical = Get-CtxPhysicalPath -Path $candidate
        if (-not $canonical) { throw "invalid profile identifier `"$Name`"" }
        $parent = Split-Path -Parent $canonical
        foreach ($trustedRoot in $trustedRoots) {
            if ([string]::Equals($parent, $trustedRoot, $comparison)) { return $canonical }
        }
        throw "invalid profile identifier `"$Name`""
    }
    throw "unknown profile `"$Name`" (looked in $($searchRoots -join ', '))"
}

function ctx {
    param(
        [Parameter(ValueFromRemainingArguments = $true)]
        [string[]]$Contexts
    )

    if (-not $Contexts -or $Contexts.Count -eq 0) {
        Show-CtxUsage
        return
    }

    switch ($Contexts[0]) {
        { $_ -in @('-h', '--help') } {
            Show-CtxUsage
            return
        }
        'current' {
            Show-CtxCurrent
            return
        }
        'check' {
            return (Test-CtxActivation)
        }
        'skills' {
            Write-CtxSkillsInventory
            return
        }
        'clear' {
            $all = $Contexts.Count -gt 1 -and $Contexts[1] -eq '--all'
            return (Clear-CtxContext -All:$all)
        }
        'load' {
            if ($Contexts.Count -lt 2 -or -not $Contexts[1]) {
                Write-Error 'ctx: error: "ctx load" requires a path argument'
                Write-Host 'Usage: ctx load <path-to-.ctx-file>'
                return
            }
            $loadFile = $Contexts[1]
            if (-not [System.IO.Path]::IsPathRooted($loadFile)) {
                $loadFile = Join-Path (Get-Location).Path $loadFile
            }
            if (-not (Test-Path -LiteralPath $loadFile -PathType Leaf)) {
                Write-Error "ctx: error: file not found: $loadFile"
                return
            }
            $loadDir = Split-Path -Parent $loadFile
            if (Import-CtxFile -CtxFile $loadFile) {
                $Script:CtxAutoLoadDir = $loadDir
                if ((Get-CtxActiveRecordMode) -ceq 'synthetic-home') {
                    return $true
                }
                return
            }
            return $false
        }
    }

    $root = Get-CtxRoot
    if (-not (Test-Path -LiteralPath $root -PathType Container)) {
        Write-Error "ctx: error: AI config root does not exist: $root"
        return
    }

    $mode = $null
    try { $mode = Get-CtxValidatedCopilotMode } catch { Write-Error "ctx: error: $_"; return }

    $profileName = $Contexts[0]
    $profileNames = @()
    $seenNames = @{}
    $dirsList = @()
    foreach ($name in $Contexts) {
        $key = $name.ToLowerInvariant()
        if ($seenNames.ContainsKey($key)) { Write-Error "ctx: error: duplicate profile `"$name`""; return }
        $seenNames[$key] = $name
        try { $profileDir = Resolve-CtxProfileIdentifier -Name $name } catch { Write-Error "ctx: error: $_"; return }
        $profileNames += $name
        $dirsList += $profileDir
    }

    # Canonical profiles are only projectable in Mode A. Reject any canonical
    # selection under Modes B/C before any environment export, workspace write,
    # or Copilot-home setup/creation (issue #48). An all-canonical Mode A
    # selection additionally requires pwsh/.NET 9+ on Unix.
    $canonicalNames = @()
    $legacyDirs = @()
    for ($ci = 0; $ci -lt $dirsList.Count; $ci++) {
        if (Test-CtxProfileCanonical -ProfileDir $dirsList[$ci]) {
            $canonicalNames += $profileNames[$ci]
        } else {
            $legacyDirs += $dirsList[$ci]
        }
    }
    if ($canonicalNames.Count -gt 0 -and $mode -cne 'synthetic-home') {
        Write-Error "ctx: error: canonical profile(s) require synthetic-home mode (active mode: $mode): $($canonicalNames -join ', ')"
        return
    }
    $allCanonical = ($canonicalNames.Count -gt 0 -and $canonicalNames.Count -eq $dirsList.Count)
    if ($mode -ceq 'synthetic-home' -and $allCanonical -and (Test-CtxUnixOldDotnet)) {
        Write-Error 'ctx: error: all-canonical Mode A requires pwsh/.NET 9+ on Unix'
        return $false
    }

    # Mode A includes only legacy roots in COPILOT_CUSTOM_INSTRUCTIONS_DIRS;
    # an all-canonical selection yields the present-empty value.
    $dirsCsv = $legacyDirs -join ','
    $sharedCsv = ""

    # COPILOT_SKILLS_DIRS is computed/validated only in Modes B/C before any
    # state change; a comma in an included skills path rejects the activation.
    # Mode A must not run this new validation or otherwise change its parsing.
    $skillsDirsCsv = $null
    if ($mode -ceq 'global-user' -or $mode -ceq 'ephemeral-clean') {
        try { $skillsDirsCsv = Get-CtxSkillsDirsCsv -ResolvedDirs $dirsList } catch { Write-Error "ctx: error: $_"; return }
    }

    $newContext = $profileNames -join '+'
    $newHome = $null
    if ($mode -ceq 'ephemeral-clean') {
        # Mode C: preflight home creation before any state change so a
        # failure leaves the previous context and all files untouched.
        try { $newHome = New-CtxEphemeralCopilotHome } catch { Write-Error "ctx: error: $_"; return }
    }
    $oldEphemeralHome = $null
    if ((Get-CtxActiveRecordMode) -ceq 'ephemeral-clean') {
        # Remember the replaced Mode C home so its retained-path notice can be
        # printed only after the replacement below actually succeeds.
        $oldEphemeralHome = $Script:CtxActiveHomeValue
    }

    if ($mode -ceq 'synthetic-home') {
        # Mode A: preflight home creation and link reconciliation before any
        # state change so a failure leaves the previous context, COPILOT_HOME,
        # and all files untouched.
        if (-not (Set-CtxCopilotHome -ContextName $newContext -ResolvedDirs $dirsList -Labels $profileNames)) {
            return $false
        }
    }

    $env:COPILOT_CUSTOM_INSTRUCTIONS_DIRS = $dirsCsv
    $env:AI_CTX_PROFILES = $newContext

    if ($mode -ceq 'global-user') {
        # Mode B: never set up or touch COPILOT_HOME at all.
    } elseif ($mode -ceq 'ephemeral-clean') {
        $env:COPILOT_HOME = $newHome
    } else {
        # Mode A: COPILOT_HOME was preflighted above before any state change;
        # no further setup needed here.
    }

    if ($mode -ceq 'global-user' -or $mode -ceq 'ephemeral-clean') {
        # B/C: export the freshly computed value; fully replaced each
        # activation, then record its exact state as ctx-owned this session.
        if ($skillsDirsCsv) { $env:COPILOT_SKILLS_DIRS = $skillsDirsCsv } else { Remove-Item Env:\COPILOT_SKILLS_DIRS -ErrorAction SilentlyContinue }
        Set-CtxActiveSkillsDirsRecord
    } else {
        # A: unset only a value that still matches what a prior B/C activation
        # in this session established; a user's own value is never touched.
        Unset-CtxOwnedSkillsDirs
    }

    # Publish the session record only after a fully successful activation.
    Set-CtxActiveRecord -Mode $mode
    Write-CtxGlobalUserHomeWarning -Mode $mode
    if ($oldEphemeralHome) {
        Write-CtxRetainedEphemeralHome -Path $oldEphemeralHome
    }

    Write-CtxStatus -ProfileName $profileName -SharedCsv $sharedCsv
    if ($mode -ceq 'synthetic-home') {
        # Only Mode A reports the documented Boolean success value for manual
        # activation; Modes B/C keep their old no-pipeline-output behavior.
        return $true
    }
}

# --- Auto-loading via .ctx files ------------------------------------------

$Script:CtxAutoLoadDir = $null
$Script:CtxLastPwd = $null
# Tracks the "home:" directive override (issue #7), if any, from the last
# .ctx file auto-loaded, so Clear-CtxContext -All knows to look for the
# synthetic COPILOT_HOME at that location instead of the centralized one.
$Script:CtxAutoLoadHomeOverride = $null
# Tracks the exact COPILOT_SKILLS_DIRS state ctx established this session
# (Modes B/C). $Script:CtxSkillsDirsOwned is $true while such a record
# exists; $Script:CtxSkillsDirsWasSet records whether the activation left the
# variable set, and $Script:CtxSkillsDirsValue records its exact value when
# set. Clear and a switch into Mode A unset the variable only when the current
# presence/value still matches this record, so a user's later value is never
# erased. Failed activations never touch the record.
$Script:CtxSkillsDirsOwned = $false
$Script:CtxSkillsDirsWasSet = $false
$Script:CtxSkillsDirsValue = $null

# Session-local activation record (no on-disk registry). Written only after
# an activation has actually succeeded; reset on clear and never on a failed
# activation. `ctx current`/`ctx check` report the mode and home of the
# matching record, never the raw selector, so a stale
# AI_CTX_PROFILES_COPILOT_MODE without a matching activation is not reported
# as active.
$Script:CtxActiveMode = $null
$Script:CtxActiveContext = $null
$Script:CtxActiveCustomDirs = $null
$Script:CtxActiveHomeWasSet = $false
$Script:CtxActiveHomeValue = $null

function Get-CtxActiveRecordMode {
    # Returns the recorded mode when the activation record's context and
    # custom-instructions directories still match the current environment, or
    # $null otherwise. COPILOT_HOME is deliberately not compared here: clear
    # and replacement notices handle Mode C home drift separately, and only
    # current/check require full record fidelity.
    if (-not $Script:CtxActiveMode) { return $null }
    if ($Script:CtxActiveContext -cne $env:AI_CTX_PROFILES) { return $null }
    if ($Script:CtxActiveCustomDirs -cne $env:COPILOT_CUSTOM_INSTRUCTIONS_DIRS) { return $null }
    return $Script:CtxActiveMode
}

